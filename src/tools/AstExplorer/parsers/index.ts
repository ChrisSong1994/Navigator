import { acorn } from './js/acorn.ts'
import { babel } from './js/babel.ts'
import { jsoncParser } from './json/jsonc.ts'
import { yamlParser } from './yaml/yaml.ts'
import type { Category } from './types.ts'

/**
 * 语言 / 解析器清单。
 *
 * 原版 12 个分类、19 个 parser：css(lightningcss/postcss/css-tree)、html(parse5/htmlparser2)、
 * graphql、markdown(remark)、sql、java、python、lua、rust(syn)，外加 js 那边的 typescript 两个。
 * 那些要么得从 CDN 拉（扩展的 CSP 不允许）、要么是 wasm、要么动不动几 MB ——
 * 这里只留三类 MVP：JavaScript/TypeScript（babel + acorn）、JSON、YAML。
 */

export const javascript: Category = {
  id: 'javascript',
  displayName: 'JavaScript',
  parsers: [babel, acorn],
  codeExample: `function tips() {
  const tips = [
    "Click on any AST node with a '+' to expand it",
    "Hovering over a node highlights the corresponding part in the source code",
    "Shift click on an AST node to expand the whole subtree",
  ];
  tips.forEach((tip, i) => console.log(\`Tip \${i}:\`, tip));
}`,
}

export const json: Category = {
  id: 'json',
  displayName: 'JSON',
  parsers: [jsoncParser],
  codeExample: `{
  "key": "value",
  "array": [1, 2, 3],
  "nested": {
    "boolean": true
  }
}`,
}

export const yaml: Category = {
  id: 'yaml',
  displayName: 'YAML',
  parsers: [yamlParser],
  codeExample: `name: astexplorer
version: 1.0.0
description: A web tool to explore the ASTs generated by various parsers.
scripts:
  start: npm start
  build: npm run build`,
}

export const categories: Category[] = [javascript, json, yaml]

export function findCategory(id: string): Category {
  return categories.find((category) => category.id === id) ?? javascript
}
